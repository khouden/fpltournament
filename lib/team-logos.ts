export function searchTeamLogos(query?: string, league?: string): TeamLogo[] {
  let filtered = TEAM_LOGOS;

  if (league && league !== "ALL") {
    filtered = filtered.filter((t) => t.league === league);
  }

  if (query && query.trim()) {
    const q = query.trim().toLowerCase();
    filtered = filtered.filter(
      (t) =>
        t.name.toLowerCase().includes(q) ||
        t.league.toLowerCase().includes(q) ||
        t.filename.toLowerCase().includes(q)
    );
  }

  return filtered;
}

/**
 * Smartly suggests a matching team logo based on a team or league name
 */
export function suggestLogoForTeamName(teamName: string): TeamLogo | null {
  if (!teamName || !teamName.trim()) return null;

  const normalized = teamName.trim().toLowerCase();
  const cleanInput = normalized.replace(/[^a-z0-9]/g, "");

  // 1. Direct exact match (name or filename)
  for (const t of TEAM_LOGOS) {
    const tNameClean = t.name.toLowerCase().replace(/[^a-z0-9]/g, "");
    const fNameClean = t.filename
      .replace(".football-logos.cc.png", "")
      .replace(".png", "")
      .replace(/[^a-z0-9]/g, "");
    if (tNameClean === cleanInput || fNameClean === cleanInput) {
      return t;
    }
  }

  // 2. Substring matching - find all matches where either contains the other, and pick the longest match
  const candidates: { logo: TeamLogo; score: number }[] = [];

  for (const t of TEAM_LOGOS) {
    const tNameLower = t.name.toLowerCase();
    const tNameClean = tNameLower.replace(/[^a-z0-9]/g, "");
    const fNameClean = t.filename
      .replace(".football-logos.cc.png", "")
      .replace(".png", "")
      .replace(/[^a-z0-9]/g, "");

    // If input contains full clean club name (e.g. "parissaintgermain" contains "parissaintgermain" -> score = length)
    if (tNameClean.length >= 3 && cleanInput.includes(tNameClean)) {
      candidates.push({ logo: t, score: tNameClean.length * 10 });
    } else if (fNameClean.length >= 3 && cleanInput.includes(fNameClean)) {
      candidates.push({ logo: t, score: fNameClean.length * 10 });
    } else if (cleanInput.length >= 4 && tNameClean.includes(cleanInput)) {
      candidates.push({ logo: t, score: cleanInput.length * 8 });
    }
  }

  if (candidates.length > 0) {
    candidates.sort((a, b) => b.score - a.score);
    return candidates[0].logo;
  }

  // 3. Word-based token match (ignoring generic club terms)
  const ignoredWords = new Set([
    "fc",
    "cf",
    "xi",
    "sc",
    "afc",
    "team",
    "club",
    "league",
    "united",
    "city",
    "town",
    "stars",
    "casuals",
    "lions",
    "dragons",
    "eagles",
    "boys",
    "bhoys",
    "premier",
  ]);

  const words = normalized
    .split(/[^a-z0-9]+/i)
    .filter((w) => w.length >= 4 && !ignoredWords.has(w));

  for (const word of words) {
    const wordMatches: { logo: TeamLogo; score: number }[] = [];
    for (const t of TEAM_LOGOS) {
      const tNameClean = t.name.toLowerCase().replace(/[^a-z0-9]/g, "");
      if (tNameClean.includes(word)) {
        wordMatches.push({ logo: t, score: word.length });
      }
    }
    if (wordMatches.length > 0) {
      wordMatches.sort((a, b) => b.score - a.score);
      return wordMatches[0].logo;
    }
  }

  return null;
}
